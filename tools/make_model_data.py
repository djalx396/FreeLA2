#!/usr/bin/env python3
# Generates Source/ModelData.h from docs/freela2_model_v0.json (the fitted model, see fit/).
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, '..', 'docs', 'freela2_model_v0.json')))
v = d['values']
lines = ['// Generated by tools/make_model_data.py from docs/freela2_model_v0.json. Do not edit by hand.',
         '#pragma once', '#include "LA2Engine.h"', '', 'namespace la2', '{',
         'static const double kModelV0[%d] = {' % len(v)]
for i in range(0, len(v), 6):
    lines.append('    ' + ', '.join(repr(float(x)) for x in v[i:i + 6]) + ',')
lines += ['};', 'inline Model makeModel() { return Model (kModelV0, %d); }' % len(v), '} // namespace la2', '']
open(os.path.join(here, '..', 'Source', 'ModelData.h'), 'w').write('\n'.join(lines))
print('ModelData.h:', len(v), 'values')
